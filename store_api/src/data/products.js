export const getProductById = (id) => {
  return products.find(p => p.id === id || p.sku.toLowerCase() === id.toLowerCase());
};

export const generateWhatsAppEnquiryLink = (product, quantity = 1, customNote = '', phoneNumber = '919876543210') => {
  const cleanPhone = phoneNumber.replace(/[^0-9]/g, '');
  const greeting = `Hi Whatshells! 🐚✨`;
  const productLine = `I would like to order: *${product.name}* (SKU: ${product.sku})`;
  const priceLine = `Price: ₹${product.price} (Qty: ${quantity}) = *₹${product.price * quantity}*`;
  const noteLine = customNote ? `Custom Note: "${customNote}"` : '';
  const ctaLine = `Could you please confirm availability and guide me through the order details?`;

  const fullMessage = [greeting, productLine, priceLine, noteLine, ctaLine]
    .filter(Boolean)
    .join('\n\n');

  const encodedMessage = encodeURIComponent(fullMessage);
  return `https://wa.me/${cleanPhone}?text=${encodedMessage}`;
};
